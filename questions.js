// 各教科・単元を100問に拡張します。
// 基礎となる問題を、選択肢の順序を変えた反復問題として展開します。
(() => {
  const source = window.DEFAULT_QUESTIONS;
  const groups = new Map();
  source.forEach(q => {
    const key = `${q.subjectId}::${q.unit}`;
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(q);
  });
  const expanded = [];
  const rotate = (items, n) => {
    if (!items.length) return [];
    const k = n % items.length;
    return [...items.slice(k), ...items.slice(0, k)];
  };
  groups.forEach((seeds, key) => {
    for (let i = 0; i < 100; i++) {
      const seed = seeds[i % seeds.length];
      const round = Math.floor(i / seeds.length) + 1;
      const choices = seed.type === 'choice' ? rotate(seed.choices, i + round) : [...(seed.choices || [])];
      expanded.push({
        ...seed,
        id: `${seed.id}_u${String(i + 1).padStart(3, '0')}`,
        question: `${seed.question}（反復 ${i + 1}）`,
        choices,
        explanation: `${seed.explanation} この問題は「${seed.unit}」の反復練習 ${i + 1}/100 です。`,
        variant: i + 1,
        sourceId: seed.id
      });
    }
  });
  window.DEFAULT_QUESTIONS = expanded;
})();
